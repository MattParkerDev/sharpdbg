#!/usr/bin/env dotnet
// Generates the Debug Adapter Protocol message types in src/SharpDbg.DapProtocol/Generated from the pinned
// debugAdapterProtocol.json schema (https://github.com/microsoft/debug-adapter-protocol, MIT licensed).
// Usage: dotnet run tools/generate-dap-protocol.cs

using System.Runtime.CompilerServices;
using System.Text;
using System.Text.Json.Nodes;

var repoRoot = Path.GetFullPath(Path.Combine(GetThisDirectory(), ".."));
var protocolDir = Path.Combine(repoRoot, "src", "SharpDbg.DapProtocol");
var schemaPath = Path.Combine(protocolDir, "debugAdapterProtocol.json");
var outputDir = Path.Combine(protocolDir, "Generated");

var schema = JsonNode.Parse(File.ReadAllText(schemaPath))!.AsObject();
var generator = new Generator(schema["definitions"]!.AsObject());
generator.Run();

Directory.CreateDirectory(outputDir);
foreach (var existing in Directory.GetFiles(outputDir, "*.g.cs")) File.Delete(existing);
foreach (var (fileName, content) in generator.Files)
{
	File.WriteAllText(Path.Combine(outputDir, fileName), content.ReplaceLineEndings("\n"));
	Console.WriteLine($"Wrote {fileName}");
}

static string GetThisDirectory([CallerFilePath] string path = "") => Path.GetDirectoryName(path)!;

sealed class Generator(JsonObject definitions)
{
	private const string Header = """
		// <auto-generated>
		// Generated by tools/generate-dap-protocol.cs from debugAdapterProtocol.json.
		// The Debug Adapter Protocol specification is Copyright (c) Microsoft Corporation, and is licensed under the
		// MIT License (code) and CC BY 4.0 (documentation). See THIRD-PARTY-NOTICES.txt.
		// Do not edit this file by hand - re-run the generator instead.
		// </auto-generated>
		#nullable enable

		using System.Collections.Generic;
		using System.Text.Json;
		using System.Text.Json.Nodes;
		using System.Text.Json.Serialization;

		namespace SharpDbg.DapProtocol;

		""";

	private static readonly HashSet<string> SkippedDefinitions = ["ProtocolMessage", "Request", "Event", "Response", "ErrorResponse"];

	// Definition names whose generated type name differs from the schema, e.g. InitializeRequestArguments -> InitializeArguments
	private readonly Dictionary<string, string> _typeNames = [];
	private readonly List<string> _serializableTypes = [];
	private readonly List<(string Command, string ArgumentsType)> _requests = [];
	private readonly List<(string EventName, string EventType)> _events = [];
	private readonly List<(string Owner, string EnumType)> _nestedEnums = [];
	private string? _currentRecord;

	public List<(string FileName, string Content)> Files { get; } = [];

	public void Run()
	{
		foreach (var (name, _) in definitions)
		{
			_typeNames[name] = name.EndsWith("RequestArguments", StringComparison.Ordinal) ? name[..^"RequestArguments".Length] + "Arguments" : name;
		}

		var requests = new StringBuilder(Header);
		var events = new StringBuilder(Header);
		var types = new StringBuilder(Header);

		foreach (var (name, node) in definitions)
		{
			if (SkippedDefinitions.Contains(name)) continue;
			var definition = node!.AsObject();
			var (baseName, body) = SplitAllOf(definition);

			switch (baseName)
			{
				case "Request":
					WriteRequest(requests, name, body);
					break;
				case "Event":
					WriteEvent(events, name, body);
					break;
				case "Response":
					// Response bodies are written alongside their request
					break;
				default:
					if (IsRequestArguments(name)) break; // written alongside their request
					WriteStandaloneType(types, name, body);
					break;
			}
		}

		Files.Add(("Requests.g.cs", requests.ToString()));
		Files.Add(("Events.g.cs", events.ToString()));
		Files.Add(("Types.g.cs", types.ToString()));
		Files.Add(("DapJsonContext.g.cs", WriteRegistry()));
	}

	private bool IsRequestArguments(string definitionName)
	{
		foreach (var (_, node) in definitions)
		{
			var (baseName, body) = SplitAllOf(node!.AsObject());
			if (baseName is not "Request") continue;
			if (RefName(body["properties"]?["arguments"]) == definitionName) return true;
		}
		return false;
	}

	private void WriteRequest(StringBuilder sb, string requestDefinitionName, JsonObject requestBody)
	{
		var command = requestBody["properties"]!["command"]!["enum"]![0]!.GetValue<string>();
		var stem = requestDefinitionName[..^"Request".Length];
		var argumentsDefinitionName = RefName(requestBody["properties"]!["arguments"]);
		var argumentsTypeName = argumentsDefinitionName is null ? stem + "Arguments" : _typeNames[argumentsDefinitionName];

		// Response type: an inline body becomes {Stem}Response, a referenced body (e.g. Capabilities) is used as-is
		var (_, responseBody) = SplitAllOf(definitions[stem + "Response"]!.AsObject());
		var responseBodySchema = responseBody["properties"]?["body"];
		string responseTypeName;
		if (RefName(responseBodySchema) is { } referencedResponse)
		{
			responseTypeName = _typeNames[referencedResponse];
		}
		else
		{
			responseTypeName = stem + "Response";
		}

		var argumentsSchema = argumentsDefinitionName is null ? new JsonObject() : SplitAllOf(definitions[argumentsDefinitionName]!.AsObject()).Body;
		WriteRecord(sb, argumentsTypeName, argumentsSchema, Description(requestBody) ?? Description(argumentsSchema),
			interfaces: $"IDapRequest<{responseTypeName}>, IDapNamedMessage",
			extraMembers:
			[
				$"static string IDapNamedMessage.MessageName => \"{command}\";",
				$"string IDapRequest.Command => \"{command}\";",
			]);
		_requests.Add((command, argumentsTypeName));

		if (RefName(responseBodySchema) is null)
		{
			WriteRecord(sb, responseTypeName, responseBodySchema?.AsObject() ?? new JsonObject(), Description(responseBody) ?? $"Response to `{command}` request.", interfaces: null, extraMembers: []);
		}
	}

	private void WriteEvent(StringBuilder sb, string eventDefinitionName, JsonObject eventBody)
	{
		var eventName = eventBody["properties"]!["event"]!["enum"]![0]!.GetValue<string>();
		var bodySchema = eventBody["properties"]?["body"]?.AsObject() ?? new JsonObject();
		WriteRecord(sb, eventDefinitionName, bodySchema, Description(eventBody),
			interfaces: "IDapEvent, IDapNamedMessage",
			extraMembers:
			[
				$"static string IDapNamedMessage.MessageName => \"{eventName}\";",
				$"string IDapEvent.Event => \"{eventName}\";",
			]);
		_events.Add((eventName, eventDefinitionName));
	}

	private void WriteStandaloneType(StringBuilder sb, string definitionName, JsonObject body)
	{
		var typeName = _typeNames[definitionName];
		if (body["type"]?.GetValue<string>() is "string")
		{
			WriteStringEnum(sb, typeName, body, indent: "");
			return;
		}
		WriteRecord(sb, typeName, body, Description(body), interfaces: null, extraMembers: []);
	}

	private void WriteRecord(StringBuilder sb, string typeName, JsonObject schema, string? description, string? interfaces, string[] extraMembers)
	{
		_serializableTypes.Add(typeName);
		_currentRecord = typeName;
		var properties = schema["properties"]?.AsObject() ?? new JsonObject();
		var required = schema["required"]?.AsArray().Select(r => r!.GetValue<string>()).ToHashSet() ?? [];
		var nested = new StringBuilder();

		WriteDocComment(sb, description, "");
		sb.Append($"public sealed partial record {typeName}");
		if (interfaces is not null) sb.Append($" : {interfaces}");
		sb.AppendLine();
		sb.AppendLine("{");

		foreach (var member in extraMembers)
		{
			sb.AppendLine($"\t{member}");
		}
		if (extraMembers.Length > 0) sb.AppendLine();

		foreach (var (jsonName, propertyNode) in properties)
		{
			var property = propertyNode!.AsObject();
			var propertyName = PascalCase(jsonName);
			if (propertyName == typeName) propertyName += "Value";
			var isRequired = required.Contains(jsonName);
			var (clrType, isValueType) = ClrType(property, propertyName, nested, "\t");

			WriteDocComment(sb, Description(property), "\t");
			sb.AppendLine($"\t[JsonPropertyName(\"{jsonName}\")]");
			var modifiers = isRequired && !isValueType ? "required " : "";
			var nullableSuffix = isRequired ? "" : "?";
			sb.AppendLine($"\tpublic {modifiers}{clrType}{nullableSuffix} {propertyName} {{ get; init; }}");
			sb.AppendLine();
		}

		sb.AppendLine("\t/// <summary>Properties not described by the protocol specification, e.g. adapter-specific launch configuration.</summary>");
		sb.AppendLine("\t[JsonExtensionData]");
		sb.AppendLine("\tpublic JsonObject? AdditionalProperties { get; set; }");

		if (nested.Length > 0)
		{
			sb.AppendLine();
			sb.Append(nested);
		}
		sb.AppendLine("}");
		sb.AppendLine();
	}

	private (string Type, bool IsValueType) ClrType(JsonObject property, string propertyName, StringBuilder nested, string indent)
	{
		if (RefName(property) is { } referenced)
		{
			var referencedDefinition = definitions[referenced]!.AsObject();
			var isEnum = referencedDefinition["type"]?.GetValue<string>() is "string";
			return (_typeNames[referenced], isEnum);
		}
		if (property["oneOf"] is not null) return ("JsonElement", true);

		if (property["type"] is JsonArray typeArray)
		{
			var kinds = typeArray.Select(t => t!.GetValue<string>()).ToHashSet();
			if (kinds.SetEquals(["integer", "string"])) return ("IntegerOrString", true);
			if (kinds.SetEquals(["string", "null"])) return ("string", false);
			return ("JsonElement", true);
		}

		var type = property["type"]?.GetValue<string>();
		switch (type)
		{
			case "string":
				if (property["enum"] is not null || property["_enum"] is not null)
				{
					var enumTypeName = propertyName + "Value";
					WriteStringEnum(nested, enumTypeName, property, indent);
					return (enumTypeName, true);
				}
				return ("string", false);
			case "boolean":
				return ("bool", true);
			case "number":
				return ("double", true);
			case "integer":
				return (IntegerType(property["format"]?.GetValue<string>(), propertyName), true);
			case "array":
				var (itemType, _) = ClrType(property["items"]!.AsObject(), propertyName, nested, indent);
				return ($"IReadOnlyList<{itemType}>", false);
			case "object":
				var additional = property["additionalProperties"];
				if (additional is JsonObject additionalSchema)
				{
					var nullableValue = additionalSchema["type"] is JsonArray;
					return (nullableValue ? "IReadOnlyDictionary<string, string?>" : "IReadOnlyDictionary<string, string>", false);
				}
				if (additional is JsonValue) return ("JsonObject", false);
				return ("JsonElement", true);
			default:
				return ("JsonElement", true);
		}
	}

	private void WriteStringEnum(StringBuilder sb, string typeName, JsonObject schema, string indent)
	{
		var values = (schema["enum"] ?? schema["_enum"])!.AsArray().Select(v => v!.GetValue<string>()).ToList();
		var descriptions = schema["enumDescriptions"]?.AsArray().Select(d => d?.GetValue<string>()).ToList();
		var isOpen = schema["enum"] is null;

		var summary = Description(schema);
		summary = (summary is null ? "" : summary + "\n") + (isOpen
			? "Known values are listed below, but other values are permitted."
			: "Values outside of the listed set are preserved, so newer peers do not break deserialization.");
		WriteDocComment(sb, summary, indent);

		sb.AppendLine($"{indent}[JsonConverter(typeof(DapStringEnumConverter<{typeName}>))]");
		sb.AppendLine($"{indent}public readonly partial record struct {typeName}(string Name) : IDapStringEnum<{typeName}>");
		sb.AppendLine($"{indent}{{");
		for (var i = 0; i < values.Count; i++)
		{
			var description = descriptions is not null && i < descriptions.Count ? descriptions[i] : null;
			WriteDocComment(sb, description ?? $"<c>{values[i]}</c>", indent + "\t");
			sb.AppendLine($"{indent}\tpublic static {typeName} {EnumMemberName(values[i])} {{ get; }} = new(\"{values[i]}\");");
		}
		sb.AppendLine();
		sb.AppendLine($"{indent}\tstatic {typeName} IDapStringEnum<{typeName}>.FromName(string name) => new(name);");
		sb.AppendLine($"{indent}\t/// <inheritdoc/>");
		sb.AppendLine($"{indent}\tpublic override string ToString() => Name;");
		sb.AppendLine($"{indent}}}");
		sb.AppendLine();
		if (indent.Length is 0) _serializableTypes.Add(typeName);
		else _nestedEnums.Add((_currentRecord!, typeName));
	}

	private string WriteRegistry()
	{
		var sb = new StringBuilder(Header);
		sb.AppendLine("internal static partial class DapMessageTypes");
		sb.AppendLine("{");
		sb.AppendLine("\tpublic static readonly IReadOnlyDictionary<string, System.Type> Requests = new Dictionary<string, System.Type>");
		sb.AppendLine("\t{");
		foreach (var (command, type) in _requests) sb.AppendLine($"\t\t[\"{command}\"] = typeof({type}),");
		sb.AppendLine("\t};");
		sb.AppendLine();
		sb.AppendLine("\tpublic static readonly IReadOnlyDictionary<string, System.Type> Events = new Dictionary<string, System.Type>");
		sb.AppendLine("\t{");
		foreach (var (eventName, type) in _events) sb.AppendLine($"\t\t[\"{eventName}\"] = typeof({type}),");
		sb.AppendLine("\t};");
		sb.AppendLine("}");
		sb.AppendLine();

		sb.AppendLine("[JsonSourceGenerationOptions(DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull, PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase)]");
		var topLevelTypes = _requests.Select(r => r.ArgumentsType)
			.Concat(_events.Select(e => e.EventType))
			.Concat(_serializableTypes)
			.Distinct();
		foreach (var type in topLevelTypes) sb.AppendLine($"[JsonSerializable(typeof({type}))]");
		foreach (var (owner, enumType) in _nestedEnums)
		{
			sb.AppendLine($"[JsonSerializable(typeof({owner}.{enumType}), TypeInfoPropertyName = \"{owner}{enumType}\")]");
			sb.AppendLine($"[JsonSerializable(typeof({owner}.{enumType}?), TypeInfoPropertyName = \"Nullable{owner}{enumType}\")]");
			sb.AppendLine($"[JsonSerializable(typeof(IReadOnlyList<{owner}.{enumType}>), TypeInfoPropertyName = \"IReadOnlyList{owner}{enumType}\")]");
		}
		sb.AppendLine("[JsonSerializable(typeof(JsonElement))]");
		sb.AppendLine("internal sealed partial class DapJsonContext : JsonSerializerContext;");
		return sb.ToString();
	}

	// Line and column numbers are specified as uint64 and small counts/indices as uint32, but are exposed as int, which is
	// what consumers work with in practice. Genuinely 64-bit quantities (memory offsets and counts) are exposed as long.
	private static readonly HashSet<string> LineAndColumnProperties = ["Line", "Column", "EndLine", "EndColumn", "Lines"];

	private static string IntegerType(string? format, string propertyName) => format switch
	{
		"int64" => "long",
		"uint64" when LineAndColumnProperties.Contains(propertyName) => "int",
		"uint64" => "long",
		_ => "int",
	};

	private static (string? BaseName, JsonObject Body) SplitAllOf(JsonObject definition)
	{
		if (definition["allOf"] is not JsonArray allOf) return (null, definition);
		var baseName = allOf.Select(a => RefName(a)).FirstOrDefault(r => r is not null);
		var body = allOf.Last(a => a!["$ref"] is null)!.AsObject();
		return (baseName, body);
	}

	private static string? RefName(JsonNode? node) =>
		node?["$ref"]?.GetValue<string>() is { } reference ? reference["#/definitions/".Length..] : null;

	private static string? Description(JsonNode? node) => node?["description"]?.GetValue<string>();

	private static string PascalCase(string jsonName)
	{
		var trimmed = jsonName.TrimStart('_');
		return char.ToUpperInvariant(trimmed[0]) + trimmed[1..];
	}

	private static string EnumMemberName(string value)
	{
		var sb = new StringBuilder();
		var upperNext = true;
		foreach (var c in value)
		{
			if (!char.IsLetterOrDigit(c))
			{
				upperNext = true;
				continue;
			}
			sb.Append(upperNext ? char.ToUpperInvariant(c) : c);
			upperNext = false;
		}
		return sb.ToString();
	}

	private static void WriteDocComment(StringBuilder sb, string? text, string indent)
	{
		if (string.IsNullOrWhiteSpace(text)) return;
		var escaped = text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;")
			.Replace("&lt;c&gt;", "<c>").Replace("&lt;/c&gt;", "</c>");
		sb.AppendLine($"{indent}/// <summary>");
		foreach (var line in escaped.ReplaceLineEndings("\n").Split('\n'))
		{
			sb.AppendLine($"{indent}/// {line}".TrimEnd());
		}
		sb.AppendLine($"{indent}/// </summary>");
	}
}
